"""Cross-language JCS conformance: the Python canonicalizer reproduces, byte-for-byte, the committed
vectors generated by the TS canonicalize (vectors/jcs-vectors.json)."""
from __future__ import annotations

import hashlib
import json
import pathlib

import pytest

from audit_chain.canonical import MAX_CANONICAL_BYTES, MAX_DEPTH, CanonicalizationError, canonicalize

_VECTORS_PATH = pathlib.Path(__file__).resolve().parents[2] / "vectors" / "jcs-vectors.json"
_FILE = json.loads(_VECTORS_PATH.read_text(encoding="utf-8"))
VECTORS = _FILE["vectors"]
TEXT_VECTORS = _FILE["text_vectors"]


def test_implements_the_normative_domain_limits() -> None:
    assert MAX_CANONICAL_BYTES == _FILE["max_canonical_bytes"]
    assert MAX_DEPTH == _FILE["max_depth"]


def test_size_limit_boundary() -> None:
    fits = "a" * (_FILE["max_canonical_bytes"] - 2)
    assert len(canonicalize(fits).encode("utf-8")) == _FILE["max_canonical_bytes"]
    with pytest.raises(CanonicalizationError):
        canonicalize(fits + "a")
    with pytest.raises(CanonicalizationError):
        canonicalize(chr(0xE9) * (_FILE["max_canonical_bytes"] // 2))


def _sha256(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def test_jcs_vectors_are_byte_identical() -> None:
    assert VECTORS, "no vectors found -- run: npm run vectors"
    for v in VECTORS:
        got = canonicalize(v["value"])
        assert got == v["expected_canonical"], (
            f'{v["name"]}: canonical mismatch\n  got: {got!r}\n  exp: {v["expected_canonical"]!r}'
        )
        assert _sha256(got) == v["expected_sha256"], f'{v["name"]}: sha256'


@pytest.mark.parametrize("v", TEXT_VECTORS, ids=[v["name"] for v in TEXT_VECTORS])
def test_text_vectors(v: dict) -> None:
    if v["expected_canonical"] is None:
        # Rejected at parse time (not JSON) or by canonicalize (outside the domain): either refuses.
        with pytest.raises((json.JSONDecodeError, CanonicalizationError)):
            canonicalize(json.loads(v["json_text"]))
        return
    got = canonicalize(json.loads(v["json_text"]))
    assert got == v["expected_canonical"]
    assert _sha256(got) == v["expected_sha256"]


@pytest.mark.parametrize("v", _FILE["size_vectors"], ids=[v["name"] for v in _FILE["size_vectors"]])
def test_size_vectors(v: dict) -> None:
    parsed = json.loads(v["prefix"] + v["unit"] * v["count"] + v["suffix"])
    if v["expected_sha256"] is None:
        with pytest.raises(CanonicalizationError):
            canonicalize(parsed)
        return
    got = canonicalize(parsed).encode("utf-8")
    assert len(got) == v["expected_bytes"]
    assert hashlib.sha256(got).hexdigest() == v["expected_sha256"]
